    <p><strong>About Kerala Police
Kerala State Police is the law enforcement agency for the state of Kerala with its headquarters at Thiruvananthapuram, the state capital.

Kerala Police has a reputation for being one of the best-managed state police forces in the country and is one of the top-ranking states in terms of maintenance of law and order. Kerala police is also one of the first police departments in South Asia to implement community policing through an enactment. It is popularly known as 'Janamaithri' Policing, which literally translates to people-friendly policing.Kerala Police registers the highest number of cognizable offences in the country, next only to the National Capital Territory of Delhi. This has to be viewed in perspective of the relatively peaceful image of the state. This is a reflection of the good practice adopted by the state in registering every cognizable offence reported at the police station level and dealing with the crimes and offenders legally.

Kerala Police has initiated several reforms and innovative schemes in the country. A new Kerala Police Act enacted in 2011 was a guiding light for many other state police forces in the country to draft their own local Police Acts. The avant-garde provisions of the Act, which enable setting up of Police Establishment Board, Police Complaints Authority, State Security Commission, Police Welfare Bureau, Community Policing, etc., have given it a status of a modern day treatise on Policing philosophy.  Student Police Cadet Scheme piloted by Kerala state during 2008-2010, to positively tackle deviant adolescent behavior and to encourage good citizenship values among youth, has been endorsed as a plan scheme by Ministry of Home Affairs and has now been adopted by many other states in India. Similarly, initiatives such as Kerala Police Cyberdome, a PPP model in cyber governance and Kerala Police CoCoN, a flagship annual conference on cyber security and digital strategies to tackle crimes, have earned a respectable place in the hearts of all stakeholders.

